public class Constantes {
    public static void main(String[] args) {
        // Constantes en java
        final int MI_CONSTANTE = 10;
        System.out.println("MI_CONSTANTE  " + MI_CONSTANTE);
        // MI_CONSTANTE = 10; arroja error ya que es una constante no se puede modificar
        // existen diferentes constantes en java como constante MATH.PI

        // constante seguntos que tiene un minuto
        final int SEGUNDOS_POR_MINUTO = 60;
        System.out.println("SEGUNDOS_POR_MINUTO = " + SEGUNDOS_POR_MINUTO);


    }
}
